@pytest.mark.group(id="Cluster name not autogenerated")
@pytest.mark.abort_on_fail
async def test_invalid_inherit_cluster_name_integration(juju: jubilant.Juju) -> None:
    """If the cluster name wasn't auto generated, cluster name should not be inherited"""
    juju.integrate(
        f"{INVALID_FAILOVER_APP}:{REL_PEER}",
        f"{MAIN_APP_NOT_AUTOGEN}:{REL_ORCHESTRATOR}",
    )

    await wait_until(
        juju,
        apps=[MAIN_APP_NOT_AUTOGEN, INVALID_FAILOVER_APP],
        apps_statuses={
            INVALID_FAILOVER_APP: [
                PeerClusterErrorDataStatuses.CANNOT_RELATE_TO_CLUSTER_WITH_DIFFERENT_NAME.value,
            ],
        },
        units_statuses={
            INVALID_FAILOVER_APP: [
                TlsStatuses.TLS_NOT_FULLY_CONFIGURED.value,
            ],
        },
        wait_for_exact_units={app: units for app, units in NON_AUTOGEN_APP_UNITS.items()},
        idle_period=IDLE_PERIOD,
    )


@pytest.mark.group(id="Cluster name autogenerated")
@pytest.mark.abort_on_fail
async def test_cluster_name_inheritence_and_integration(juju: jubilant.Juju) -> None:
    """Data and failover apps should inherit cluster name and integrate with cluster manager."""
    juju.integrate(f"{DATA_APP_AUTOGEN}:{REL_PEER}", f"{MAIN_APP_AUTOGEN}:{REL_ORCHESTRATOR}")

    await wait_until(
        juju,
        apps=[MAIN_APP_AUTOGEN, DATA_APP_AUTOGEN],
        wait_for_exact_units={
            app: AUTOGEN_APP_UNITS[app] for app in [MAIN_APP_AUTOGEN, DATA_APP_AUTOGEN]
        },
        idle_period=IDLE_PERIOD,
    )

    juju.integrate(f"{FAILOVER_APP_AUTOGEN}:{REL_PEER}", f"{MAIN_APP_AUTOGEN}:{REL_ORCHESTRATOR}")
    juju.integrate(f"{DATA_APP_AUTOGEN}:{REL_PEER}", f"{FAILOVER_APP_AUTOGEN}:{REL_ORCHESTRATOR}")

    await wait_until(
        juju,
        apps=[MAIN_APP_AUTOGEN, DATA_APP_AUTOGEN, FAILOVER_APP_AUTOGEN],
        wait_for_exact_units={
            app: AUTOGEN_APP_UNITS[app]
            for app in [MAIN_APP_AUTOGEN, DATA_APP_AUTOGEN, FAILOVER_APP_AUTOGEN]
        },
        idle_period=IDLE_PERIOD,
    )

    # make sure data can be written
    c_writes = ContinuousWrites(juju, app=DATA_APP_AUTOGEN)
    await c_writes.start()
    time.sleep(30)
    await c_writes.stop()
    assert (await c_writes.count()) > 0, "Continuous writes did not increase"

    leader_unit_ip = await get_leader_unit_ip(juju, app=MAIN_APP_AUTOGEN)
    nodes = await all_nodes(juju, leader_unit_ip, app=MAIN_APP_AUTOGEN)
    assert len(nodes) == 4, f"Wrong node count. Expecting 4 online nodes, found: {len(nodes)}."
