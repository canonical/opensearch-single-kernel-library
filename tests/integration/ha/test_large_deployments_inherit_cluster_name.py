logger = logging.getLogger(__name__)

REL_ORCHESTRATOR = "peer-cluster-orchestrator"
REL_PEER = "peer-cluster"

MAIN_APP_NOT_AUTOGEN = "opensearch-main"
INVALID_FAILOVER_APP = "opensearch-failover-invalid"

MAIN_APP_AUTOGEN = "opensearch-main-autogen"
FAILOVER_APP_AUTOGEN = "opensearch-failover-autogen"
DATA_APP_AUTOGEN = "opensearch-data-autogen"

CLUSTER_NAME = "log-app"

NON_AUTOGEN_APP_UNITS = {
    MAIN_APP_NOT_AUTOGEN: 1,
    INVALID_FAILOVER_APP: 1,
}

AUTOGEN_APP_UNITS = {
    MAIN_APP_AUTOGEN: 1,
    FAILOVER_APP_AUTOGEN: 1,
    DATA_APP_AUTOGEN: 2,
}

NO_DATA_NODE_STATUS_MESSAGE = "Missing requirements: At least 1 data nodes are required."
NO_CM_STATUS_MESSAGE = "Missing requirements: At least 1 cluster manager nodes are required."


NO_DATA_NODE_STATUS = StatusObject(
    status="blocked",
    message="Missing requirements: At least 1 data nodes are required.",
)
NO_CM_STATUS = StatusObject(
    status="blocked",
    message="Missing requirements: At least 1 cluster manager nodes are required.",
)


@pytest.mark.group(id="Cluster name not autogenerated")
@pytest.mark.abort_on_fail
@pytest.mark.skip_if_deployed
async def test_build_and_deploy_not_autogen(juju: jubilant.Juju, charm, series) -> None:
    """Build and deploy one unit of OpenSearch without autogenerated cluster name."""
    # it is possible for users to provide their own cluster for HA testing.
    # Hence, check if there is a pre-existing cluster.
    juju.model_config(MODEL_CONFIG)

    # Deploy TLS Certificates operator.
    config = {"ca-common-name": "CN_CA"}
    juju.deploy(TLS_CERTIFICATES_APP_NAME, channel=TLS_STABLE_CHANNEL, config=config)
    juju.deploy(
        charm,
        app=MAIN_APP_NOT_AUTOGEN,
        num_units=1,
        base=_series_to_base(series),
        config={"cluster_name": CLUSTER_NAME} | CONFIG_OPTS,
    )
    juju.deploy(
        charm,
        app=INVALID_FAILOVER_APP,
        num_units=1,
        base=_series_to_base(series),
        config={"init_hold": True, "roles": "cluster_manager"} | CONFIG_OPTS,
    )

    # wait until the TLS operator is ready
    await wait_until(
        juju,
        apps=[TLS_CERTIFICATES_APP_NAME],
        wait_for_exact_units={TLS_CERTIFICATES_APP_NAME: 1},
        idle_period=IDLE_PERIOD,
    )

    # integrate TLS to all applications
    for app in [
        MAIN_APP_NOT_AUTOGEN,
        INVALID_FAILOVER_APP,
    ]:
        juju.integrate(app, TLS_CERTIFICATES_APP_NAME)

    # confirm all apps are blocked due to missing data node or waiting for relation
    await wait_until(
        juju,
        apps=list(NON_AUTOGEN_APP_UNITS.keys()),
        apps_statuses={
            INVALID_FAILOVER_APP: [PeerClusterStatuses.PEER_CLUSTER_NO_RELATION.value],
        },
        units_statuses={
            INVALID_FAILOVER_APP: [NO_DATA_NODE_STATUS],
        },
        wait_for_exact_units={app: units for app, units in NON_AUTOGEN_APP_UNITS.items()},
        idle_period=IDLE_PERIOD,
        timeout=1800,
    )


